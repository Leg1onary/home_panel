import assert from 'node:assert/strict';
import {numericReading,stateTimes} from '../src/readings.js';
import {scenePins} from '../src/scene-pins.js';
import {defaultPreferences} from '../src/preferences.js';
import {migrateHouseProfile} from '../src/house-profile.js';
const now=Date.now(),old=new Date(now-34*60000).toISOString();
const e={entity_id:'sensor.temperature',state:'26.9',last_changed:old,last_updated:old,attributes:{unit_of_measurement:'°C'}};
let result=numericReading(e,{unit:'°C',now});
assert.equal(result.available,true);assert.equal(result.value,26.9);
assert.equal(result.updatedAt,Date.parse(old));assert.equal(result.reportedAt,null);
assert.equal(numericReading({...e,last_updated:new Date(now-86400000).toISOString()},{unit:'°C',now}).available,true);
assert.equal(numericReading({state:'0',attributes:e.attributes},{unit:'°C',now}).value,0);
assert.equal(numericReading({...e,last_changed:undefined,last_updated:undefined},{unit:'°C',now}).available,true);
assert.equal(numericReading({...e,last_changed:undefined,last_updated:undefined},{unit:'°C',now}).reportedAt,null);
for(const state of ['unknown','unavailable','',' ','NaN','Infinity','foo'])assert.equal(numericReading({...e,state},{unit:'°C',now}).available,false,state);
assert.equal(numericReading(e,{online:false,unit:'°C',now}).available,false);
assert.equal(numericReading(null,{unit:'°C',now}).available,false);
assert.equal(numericReading({...e,attributes:{unit_of_measurement:'°F'}},{unit:'°C',now}).available,false);
assert.equal(stateTimes({...e,last_reported:new Date(now+120000).toISOString()},now).reportedAt,null);
result=numericReading({...e,last_reported:new Date(now).toISOString()},{unit:'°C',now});
assert.equal(result.reportedAt,now);assert.equal(result.updatedAt,Date.parse(old),'A new write does not manufacture a value change');
const p=migrateHouseProfile(defaultPreferences());p.mode='live';p.view='home';p.liveOnline=true;
p.bindings['temperature:living'].verified=true;
p.entityStates={[p.bindings['temperature:living'].entityId]:e};
assert.equal(scenePins(p,now).find(p=>p.kind==='climate')?.label,'26.9°');
p.liveOnline=false;assert.equal(scenePins(p,now).some(p=>p.kind==='climate'),false);
p.liveOnline=true;p.bindings['temperature:living'].verified=false;
assert.equal(scenePins(p,now).some(p=>p.kind==='climate'),false);
console.log('PASS: stable and untimestamped HA values remain visible, provenance is not polling, zero/units/offline/unknown validation and verified scene pins.');
